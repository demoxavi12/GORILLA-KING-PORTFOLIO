// Tiny inline placeholders for the intro wall, so its first paint is already the photographs.
// node scripts/lqip.mjs  → src/data/lqip.ts
import sharp from "sharp";
import fs from "node:fs";
const files = fs.readdirSync("public/archive").filter((f) => f.endsWith(".webp")).sort();
const out = {};
for (const f of files) {
  const buf = await sharp(`public/archive/${f}`).resize(12).webp({ quality: 40 }).toBuffer();
  out[`/archive/${f}`] = `data:image/webp;base64,${buf.toString("base64")}`;
}
fs.writeFileSync(
  "src/data/lqip.ts",
  `/** Generated by scripts/lqip.mjs — 12px placeholders painted before the photographs load. */\nexport const lqip: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(files.length, "placeholders,", fs.statSync("src/data/lqip.ts").size, "bytes");
